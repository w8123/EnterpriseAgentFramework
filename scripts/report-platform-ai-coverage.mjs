export function normalizeRoute(route) {
  return route.replace(/\{[^}]+\}/g, '{}')
}

export function makeReport(inventory, registeredTools, links = LINKS, storageClasses = STORAGE_CLASSES, unopened = UNOPENED) {
  const registry = new Map()
  for (const [method, route, tool, limitation] of links) {
    const key = `${method} ${route}`
    if (registry.has(key)) throw new Error(`duplicate platform AI surface link: ${key}`)
    if (!registeredTools.has(tool)) throw new Error(`platform AI tool is missing: ${tool}`)
    registry.set(key, { tool, limitation })
    if (unopened[key]) throw new Error(`route has a platform AI tool but is still listed as unopened: ${key}`)
  }
  const sites = inventory.sites.filter(site => site.surface === 'admin-frontend').map(site => {
    const key = `${site.method} ${normalizeRoute(site.path)}`
    const link = site.pathResolved && site.methodResolved ? registry.get(key) : undefined
    return { ...site, relatedTool: link?.tool ?? null, limitation: link?.limitation ?? null }
  })
  const storage = inventory.storageSites.filter(site => site.surface === 'admin-frontend')
  const unmapped = new Map()
  for (const site of sites) {
    if (site.relatedTool) continue
    const key = `${site.method} ${normalizeRoute(site.path)}${site.pathResolved && site.methodResolved ? '' : ' [unresolved]'}`
    unmapped.set(key, (unmapped.get(key) ?? 0) + 1)
  }
  return {
    scope: 'Frontend request sites only. A related tool is partial evidence, not task parity or runtime acceptance.',
    totalSites: sites.length,
    sitesWithRelatedTool: sites.filter(site => site.relatedTool).length,
    sitesWithoutRelatedTool: sites.filter(site => !site.relatedTool).length,
    unresolvedSites: sites.filter(site => !site.pathResolved || !site.methodResolved).length,
    browserStorageSites: storage.length,
    browserStorageByClass: Object.fromEntries([...storage.reduce((counts, site) => {
      const kind = storageClasses[site.file]?.[0] ?? 'unclassified'
      return counts.set(kind, (counts.get(kind) ?? 0) + 1)
    }, new Map())].sort(([a], [b]) => a.localeCompare(b))),
    unclassifiedStorageFiles: [...new Set(storage.filter(site => !storageClasses[site.file]).map(site => site.file))].sort(),
    unmappedByReason: Object.fromEntries([...[...unmapped.keys()].reduce((counts, route) => {
      const kind = unopened[route]?.[0] ?? 'unclassified'
      return counts.set(kind, (counts.get(kind) ?? 0) + 1)
    }, new Map())].sort(([a], [b]) => a.localeCompare(b))),
    unclassifiedUnmappedRoutes: [...unmapped.keys()].filter(route => !unopened[route]).sort(),
    staleUnopenedRoutes: Object.keys(unopened).filter(route => !unmapped.has(route)).sort(),
    unmappedRoutes: [...unmapped.entries()].sort(([a], [b]) => a.localeCompare(b))
      .map(([route, count]) => ({ route, count, reason: unopened[route] ?? null })),
    sites,
  }
}

export function registeredPlatformTools(source) {
  return new Set([...source.matchAll(/new Tool\("([A-Za-z0-9_]+)"/g)].map(match => match[1]))
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const root = process.cwd()
  const source = fs.readFileSync(path.join(root,
    'reachai-control-service/src/main/java/com/enterprise/ai/control/mcp/application/platform/McpPlatformProtocolService.java'), 'utf8')
  const report = makeReport(buildInventory(root), registeredPlatformTools(source))
  if (process.argv.includes('--json')) {
    console.log(JSON.stringify(report, null, 2))
  } else {
    const { sites, unmappedRoutes, ...summary } = report
    console.log(JSON.stringify({ ...summary, uniqueUnmappedRoutes: unmappedRoutes.length }, null, 2))
    console.log('Use --json for mapped and unmapped request sites; browser storage is classified by STORAGE_CLASSES; unclassified files still need review.')
  }
}
