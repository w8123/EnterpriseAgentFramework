/**
 * Generate a self-contained index.d.ts for @reachai/embed-chat from real SDK sources.
 * Fact source: src/sdk/index.ts public surface (eafPageBridge + eafChat + defineReachAiChatElement).
 * Output must not reference package-relative modules that are absent from the tarball.
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const ts = require('typescript')

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sdkDir = resolve(root, 'src', 'sdk')
const outPath = resolve(root, 'dist-sdk', 'embed-chat', 'index.d.ts')

function readSource(filePath) {
  const text = ts.sys.readFile(filePath)
  if (!text) throw new Error(`Missing SDK source: ${filePath}`)
  return text
}

function isExported(node) {
  return Boolean(node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword))
}

function printNode(sourceFile, node) {
  const printer = ts.createPrinter({
    newLine: ts.NewLineKind.LineFeed,
    removeComments: false,
  })
  return printer.printNode(ts.EmitHint.Unspecified, node, sourceFile).trim()
}

function parameterText(sourceFile, param) {
  // Ambient declarations cannot keep initializer defaults (e.g. `options = {}`).
  const optional = param.questionToken || param.initializer ? '?' : ''
  const name = param.name.getText(sourceFile)
  const type = param.type ? `: ${param.type.getText(sourceFile)}` : ''
  const rest = param.dotDotDotToken ? '...' : ''
  return `${rest}${name}${optional}${type}`
}

function toFunctionDeclaration(sourceFile, node) {
  const name = node.name?.getText(sourceFile)
  if (!name) return null
  const typeParams = node.typeParameters
    ? `<${node.typeParameters.map((p) => p.getText(sourceFile)).join(', ')}>`
    : ''
  const params = node.parameters.map((p) => parameterText(sourceFile, p)).join(', ')
  const returnType = node.type ? `: ${node.type.getText(sourceFile)}` : ''
  // Drop async keyword; keep Promise<> return type from the annotation.
  return `export function ${name}${typeParams}(${params})${returnType};`
}

function parse(filePath) {
  return ts.createSourceFile(filePath, readSource(filePath), ts.ScriptTarget.ES2020, true, ts.ScriptKind.TS)
}

function exportedFunctions(sourceFile, name) {
  return sourceFile.statements.filter(
    (stmt) =>
      ts.isFunctionDeclaration(stmt) &&
      isExported(stmt) &&
      stmt.name?.getText(sourceFile) === name,
  )
}

function extractTypes(sourceFile) {
  const chunks = []
  for (const stmt of sourceFile.statements) {
    if ((ts.isInterfaceDeclaration(stmt) || ts.isTypeAliasDeclaration(stmt)) && isExported(stmt)) {
      chunks.push(printNode(sourceFile, stmt))
    }
  }
  return chunks
}

function extractFunctions(sourceFile, { skipNames = new Set() } = {}) {
  const chunks = []
  const names = new Set()
  for (const stmt of sourceFile.statements) {
    if (!ts.isFunctionDeclaration(stmt) || !isExported(stmt) || !stmt.name) continue
    names.add(stmt.name.getText(sourceFile))
  }
  for (const name of names) {
    if (skipNames.has(name)) continue
    const decls = exportedFunctions(sourceFile, name)
    const overloads = decls.filter((d) => !d.body)
    const impl = decls.find((d) => d.body)
    if (overloads.length > 0) {
      for (const overload of overloads) {
        chunks.push(toFunctionDeclaration(sourceFile, overload))
      }
    } else if (impl) {
      chunks.push(toFunctionDeclaration(sourceFile, impl))
    }
  }
  return chunks.filter(Boolean)
}

const parts = []
parts.push('/**')
parts.push(' * Auto-generated public types for @reachai/embed-chat.')
parts.push(' * Source of truth: src/sdk/{eafPageBridge,embedSession,eafChat}.ts and index.ts export of defineReachAiChatElement.')
parts.push(' * Regenerated by scripts/generate-embed-chat-dts.mjs during build:sdk — do not hand-edit.')
parts.push(' */')
parts.push('')

const seen = new Set()
function pushUnique(chunk) {
  if (!chunk) return
  const key = chunk.replace(/\s+/g, ' ').trim()
  if (!key || seen.has(key)) return
  seen.add(key)
  parts.push(chunk)
  parts.push('')
}

const pageBridge = parse(resolve(sdkDir, 'eafPageBridge.ts'))
const embedSession = parse(resolve(sdkDir, 'embedSession.ts'))
const themePresets = parse(resolve(sdkDir, 'themePresets.ts'))
const eafChat = parse(resolve(sdkDir, 'eafChat.ts'))

for (const chunk of extractTypes(pageBridge)) pushUnique(chunk)
for (const chunk of extractFunctions(pageBridge)) pushUnique(chunk)

for (const chunk of extractTypes(embedSession)) pushUnique(chunk)
for (const chunk of extractFunctions(embedSession)) pushUnique(chunk)

for (const chunk of extractTypes(themePresets)) pushUnique(chunk)
for (const chunk of extractFunctions(themePresets)) pushUnique(chunk)
// Ambient const for preset table — keep shape stable for consumers.
pushUnique(`export declare const EAF_CHAT_THEME_PRESETS: {
  readonly 'tech-purple': { readonly primary: "#6366f1"; readonly rgb: "99 102 241"; };
  readonly 'metro-green': { readonly primary: "#0b7a59"; readonly rgb: "11 122 89"; };
  readonly 'aurora-cyan': { readonly primary: "#0891b2"; readonly rgb: "8 145 178"; };
  readonly 'nebula-violet': { readonly primary: "#7c3aed"; readonly rgb: "124 58 237"; };
  readonly 'coral-rose': { readonly primary: "#db2777"; readonly rgb: "219 39 119"; };
  readonly 'solar-gold': { readonly primary: "#b45309"; readonly rgb: "180 83 9"; };
  readonly 'deep-ocean': { readonly primary: "#1d4ed8"; readonly rgb: "29 78 216"; };
};`)
pushUnique('export declare const EAF_CHAT_DEFAULT_THEME_PRESET: EafChatThemePreset;')

for (const chunk of extractTypes(eafChat)) pushUnique(chunk)
for (const chunk of extractFunctions(eafChat, { skipNames: new Set(['buildEafChatSessionPayload']) })) {
  pushUnique(chunk)
}

// Public export from src/sdk/index.ts (Vue CE implementation is bundled into index.mjs, not shipped as .d.ts deps).
pushUnique('export function defineReachAiChatElement(tagName?: string): void;')

await mkdir(dirname(outPath), { recursive: true })
const body = `${parts.join('\n').trim()}\n`
await writeFile(outPath, body, 'utf8')

// Guardrails: refuse obsolete bridge APIs and require current ones.
const required = [
  'readonly pageInstanceId',
  'readonly route',
  'readonly registeredActions',
  'readonly actionDefinitions',
  'registerAction(',
  'handleEvent(',
  'onResult(',
  'onActionDefinitionsChange(',
  'buildEafChatSessionPayload(bridge: EafPageBridge, page?: EafPageDescriptor)',
  'resolveEafChatEmbedApiRoot',
  'resolveEafChatPlatformBase',
  'createEafChat(',
  'EafChatTokenProviderContext',
  'EafChatAuthState',
  'tokenTimeoutMs?: number',
  'retry(): Promise<void>',
  'EafChatThemePreset',
  'resolveEafChatThemePrimary',
  "preset?: EafChatThemePreset",
  'EAF_CHAT_THEME_PRESETS',
]
for (const token of required) {
  if (!body.includes(token)) {
    throw new Error(`[generate-embed-chat-dts] missing required public surface: ${token}`)
  }
}
// Forbid obsolete members on EafPageBridge only (EafChatClient.destroy is valid).
const bridgeMatch = body.match(/export interface EafPageBridge \{([\s\S]*?)\n\}/)
if (!bridgeMatch) {
  throw new Error('[generate-embed-chat-dts] EafPageBridge interface missing')
}
const bridgeBody = bridgeMatch[1]
for (const token of ['unregister(', 'destroy(', 'list(', 'execute(']) {
  if (bridgeBody.includes(token)) {
    throw new Error(`[generate-embed-chat-dts] forbidden obsolete Bridge API: ${token}`)
  }
}
if (/\bregister\s*\(/.test(bridgeBody.replace(/registerAction\s*\(/g, ''))) {
  throw new Error('[generate-embed-chat-dts] forbidden obsolete Bridge register() leaked into d.ts')
}

console.log(`[generate-embed-chat-dts] wrote ${outPath} (${body.length} bytes)`)
