async function render(mode: ClassificationEditorProps['mode'] = 'description', extras: Partial<ClassificationEditorProps> = {}, closeAutoFocus?: () => void) {
  const props = reactive<ClassificationEditorProps>({ visible: true, projectId: 7, projectCode: 'orders', groups: [group(2), group(3), group(4)], group: group(), mode, ...extras })
  const updated = vi.fn()
  const Host = defineComponent({ setup: () => () => h(CatalogClassificationEditor, { ...props, 'onUpdate:visible': (value: boolean) => { props.visible = value }, onUpdated: updated,
    ...(closeAutoFocus ? { onCloseAutoFocus: closeAutoFocus } : {}) }) })
  const router = createRouter({ history: createMemoryHistory(), routes: [{ path: '/', component: Host }, { path: '/other', component: { template: '<p>其他页面</p>' } }] })
  await router.push('/')
  const wrapper = mount(defineComponent({ setup: () => () => h(RouterView) }), { global: { plugins: [router, ElementPlus] } })
  mounted.push(wrapper); await flushPromises()
  const editor = wrapper.findComponent(CatalogClassificationEditor)
  const button = (label: string) => editor.findAll('button').find(item => item.text() === label)!
  return { wrapper, editor, button, props, router, updated }
}

